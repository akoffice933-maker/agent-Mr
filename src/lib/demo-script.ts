// Сценарии демо-агента на лендинге.
//
// Данные ЗАХАРДКОЖЕНЫ намеренно, и это единственное место в проекте, где так
// можно. Демо на публичной странице не имеет права ходить в БД: /welcome —
// ISR-страница для анонимного трафика с рекламы (ТЗ §5.1), а живой запрос к
// агенту потребовал бы сессии, tenant-контекста и оплаты токенов LLM за
// каждого случайного посетителя.
//
// Честность важнее эффектности: цифры ниже — правдоподобный пример, и подпись
// под демо прямо называет его демонстрацией на условных данных. Обещать
// «вот ваши кампании» до подключения кабинета было бы враньём.
//
// Порог подтверждения (approvalRub) и суммы согласованы с реальными дефолтами
// safety-настроек: изменение бюджета всегда проходит через предпросмотр.

export interface DemoRow {
  /** Название кампании в кабинете. */
  name: string;
  /** Площадка — совпадает с ключами PLATFORM_LABEL на лендинге. */
  platform: "g" | "y" | "a";
  /** Текущее состояние метрики, из-за которого кампания попала в выборку. */
  metric: string;
  /** Что агент предлагает сделать. */
  action: string;
}

export interface DemoScenario {
  id: string;
  /** Реплика пользователя — то, что он «написал» агенту. */
  prompt: string;
  /** Короткий ярлык для кнопки выбора сценария. */
  chip: string;
  /** Первая реплика агента до таблицы предпросмотра. */
  intro: string;
  rows: DemoRow[];
  /** Итог: что изменится в деньгах. */
  impact: string;
  /** Строка про дневной лимит — показывает, что у агента есть потолок. */
  budgetNote: string;
  /** Ответ после подтверждения: что реально произошло. */
  applied: string;
  /** Что записано в журнал действий — механизм, а не украшение. */
  audit: string;
}

